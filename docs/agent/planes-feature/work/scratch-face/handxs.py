def draw(rows, cut_path, out):
    text = '\n'.join(layout([i for i in r if i[1]]) for r in rows)
    cut = Image.open(cut_path).convert('RGB').resize((W, W))
    ov = T.render(text, (W, len(rows) * 18), Image.blend(cut, Image.new('RGB', cut.size, 'white'), 0.5).crop((0, 0, W, len(rows) * 18)), (220, 0, 0))
    clean = T.render(text, (W, len(rows) * 18))
    S = Image.new('RGB', (W * 3 + 20, len(rows) * 18), 'white'); S.paste(cut.crop((0, 0, W, len(rows) * 18)), (0, 0)); S.paste(ov, (W + 10, 0)); S.paste(clean, (2 * W + 20, 0))
    S = S.resize((S.size[0] * 2, S.size[1] * 2)); S.save(out)
    print(out, 'law:', check(text) or 'ok')
    return text


